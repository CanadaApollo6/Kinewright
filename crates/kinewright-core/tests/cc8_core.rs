/// **§2.4.** Declared static HDR metadata serialises with its provenance,
/// round-trips exactly, and is absent from a description that has none.
///
/// §2.4: "Mastering-display primaries and MaxCLL/MaxFALL are read on probe
/// where the container carries them, **stored on the source description with
/// provenance**, and reported. They are never invented: absent metadata is
/// `Unknown` and stays `Unknown`."
///
/// The values are asserted in ST 2086's own integer units, which is how they
/// are stored: a declared value is the integer the bitstream carried, so
/// nothing here rounds and nothing is reconstructed from a float.
#[test]
fn cc8_declared_static_hdr_metadata_round_trips_with_its_provenance() {
    let description = ColorDescription {
        hdr_static_metadata: declared_static_metadata(),
        ..hlg_source_description()
    };
    let encoded = serde_json::to_value(&description).expect("it serialises");
    let metadata = &encoded["hdr_static_metadata"];
    assert_eq!(metadata["mastering_display"]["red"]["x_increments"], 34_000);
    assert_eq!(metadata["mastering_display"]["red"]["y_increments"], 16_000);
    assert_eq!(
        metadata["mastering_display"]["green"]["x_increments"],
        13_250
    );
    assert_eq!(metadata["mastering_display"]["blue"]["y_increments"], 3_000);
    assert_eq!(
        metadata["mastering_display"]["white_point"]["x_increments"],
        15_635
    );
    assert_eq!(
        metadata["mastering_display"]["min_luminance_ten_thousandths_nits"],
        1
    );
    assert_eq!(
        metadata["mastering_display"]["max_luminance_ten_thousandths_nits"],
        10_000_000
    );
    assert_eq!(
        metadata["mastering_display"]["provenance"],
        "container_metadata"
    );
    assert_eq!(metadata["content_light_level"]["max_cll_nits"], 1_000);
    assert_eq!(metadata["content_light_level"]["max_fall_nits"], 400);
    assert_eq!(
        metadata["content_light_level"]["provenance"],
        "stream_metadata"
    );

    let decoded: ColorDescription = serde_json::from_value(encoded).expect("it round-trips");
    assert_eq!(decoded, description);

    // A description with no declaration writes no field at all, which is what
    // keeps §7 item 1's byte-unchanged obligation true for every pre-CC8
    // project.
    let unknown = ColorDescription::unknown();
    assert!(unknown.hdr_static_metadata.is_unknown());
    let encoded = serde_json::to_string(&unknown).expect("it serialises");
    assert!(!encoded.contains("hdr_static_metadata"), "{encoded}");
    let decoded: ColorDescription = serde_json::from_str(&encoded).expect("it round-trips");
    assert_eq!(decoded, unknown);

    // §2.4 forbids inventing a value, so a partially written block is a typed
    // deserialization failure rather than a source that declared zero nits.
    let truncated = serde_json::json!({
        "primaries": "bt2020",
        "hdr_static_metadata": { "content_light_level": { "max_cll_nits": 1000 } },
    });
    serde_json::from_value::<ColorDescription>(truncated)
        .expect_err("a half-written light-level block must not default to zero");

    // Declared metadata is source-side evidence and changes no target-side
    // answer: it is not part of §5.3's check order, and it does not make a
    // description stop being §5.1's lane.
    let lane_with_metadata = ColorDescription {
        hdr_static_metadata: declared_static_metadata(),
        ..cc8_hdr_delivery_description()
    };
    assert!(
        kinewright_core::delivery_color_mismatches(&lane_with_metadata).is_empty(),
        "§5.3's vocabulary and check order are unchanged by §2.4",
    );
}

/// **§5.1.** The core's HDR delivery description is the authority table's row.
///
/// The constructor writes typed enum values; the table stores wire spellings.
/// Asserting them equal here is what lets `ColorContext::hdr_hlg_rec2020` be
/// written from the enums without becoming a second transcription of §5.1.
#[test]
fn cc8_hdr_delivery_description_is_section_5_1s_lane_table() {
    let description = cc8_hdr_delivery_description();
    let lane = CC8_HDR_DELIVERY_LANE;
    assert_eq!(description.primaries.wire(), lane.primaries);
    assert_eq!(description.transfer.wire(), lane.transfer);
    assert_eq!(description.matrix.wire(), lane.matrix);
    assert_eq!(description.range.wire(), lane.range);
    assert_eq!(description.white_point.wire(), lane.white_point);
    assert_eq!(
        description.bit_depth.integer_bits(),
        Some(lane.bit_depth_bits)
    );
    assert_eq!(description.provenance, ColorProvenance::ApplicationDefault);
    assert!(description.hdr_static_metadata.is_unknown());
    assert_eq!(
        DeliveryLane::for_description(&description),
        DeliveryLane::HdrHlgRec2020
    );
    assert!(kinewright_core::delivery_color_mismatches(&description).is_empty());
}

