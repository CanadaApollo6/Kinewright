/// **§9.1 fixture 11 / §7 item 1.** Every pre-CC8 project opens byte-unchanged.
///
/// §7 item 1: "**Every existing project opens byte-unchanged and exports
/// byte-identically.** This is the strongest migration obligation in CC8 and §9
/// gates it. An SDR project must not acquire an HDR field, a changed delivery
/// description, or a different exported byte stream."
///
/// All three prohibitions are asserted, and the first one is asserted on the
/// **bytes** rather than on a field list, because a field list can only refuse
/// the fields its author thought of:
///
/// 1. the re-serialized document is byte-identical to the stored file;
/// 2. no CC8 spelling appears anywhere in those bytes; and
/// 3. the loaded delivery description and pipeline state are the ones the file
///    stored, and the project is still CC1-managed-SDR-compatible.
#[test]
fn cc8_pre_cc8_projects_open_byte_unchanged_and_acquire_no_hdr_field() {
    for (label, raw) in [
        ("sdr", PRE_CC8_SDR_PROJECT),
        (
            "hdr_source_sdr_delivery",
            PRE_CC8_HDR_SOURCE_SDR_DELIVERY_PROJECT,
        ),
    ] {
        let document: Document = serde_json::from_str(raw).expect("a pre-CC8 project opens");
        document.validate().expect("and it validates");

        let saved = format!(
            "{}\n",
            serde_json::to_string_pretty(&document).expect("and it saves")
        );
        assert_eq!(
            saved, raw,
            "{label}: a pre-CC8 project must re-save byte-for-byte",
        );

        for spelling in [
            "hdr_static_metadata",
            "managed_hdr_v1",
            "mastering_display",
            "content_light_level",
        ] {
            assert!(
                !saved.contains(spelling),
                "{label}: a pre-CC8 project acquired the CC8 field `{spelling}`",
            );
        }

        // The stored state, unchanged, and CC1's own question still answered
        // the way CC1 answers it.
        assert_eq!(
            document.color_context.pipeline_state,
            ColorPipelineState::ManagedSdrV1,
            "{label}",
        );
        assert_eq!(
            document.color_context.delivery,
            ColorContext::sdr_rec709().delivery,
            "{label}: the delivery description must not have moved",
        );
        assert!(
            document.color_context.is_managed_sdr_compatible(),
            "{label}"
        );
        assert!(
            !document.color_context.is_managed_hdr_compatible(),
            "{label}"
        );
        assert_eq!(
            DeliveryLane::for_description(&document.color_context.delivery),
            DeliveryLane::SdrRec709,
            "{label}",
        );

        // §2.4: absent metadata is unknown and stays unknown.
        for asset in &document.media_pool {
            assert!(
                asset.color_description.hdr_static_metadata.is_unknown(),
                "{label}: asset {} acquired declared HDR metadata",
                asset.id,
            );
        }

        // The compact form round-trips too, and a second load of what this
        // build wrote is the same document — the reopen half of §7 item 4.
        let compact = serde_json::to_string(&document).expect("compact save");
        let reopened: Document = serde_json::from_str(&compact).expect("compact reopen");
        assert_eq!(reopened, document, "{label}");
        assert_eq!(
            serde_json::to_string(&reopened).expect("compact re-save"),
            compact,
            "{label}",
        );
    }
}

/// **§9.1 fixture 11, second sentence / §7 item 2.** An HDR-source project on
/// an SDR delivery target loads and blocks with the typed reason.
///
/// §7 item 2: "A project whose source is HDR but whose delivery is SDR
/// **loads**, reports the mismatch, and blocks managed export with the §5.3
/// typed reason naming the deferral. It is not auto-tone-mapped and its
/// delivery target is not silently rewritten (§0.2 Q6)."
///
/// Each clause is a separate assertion, including the two negative ones: after
/// the report is taken, the document's delivery description and its source
/// description are compared against the bytes it was loaded from.
#[test]
fn cc8_pre_cc8_hdr_source_on_sdr_delivery_loads_and_blocks_with_the_typed_reason() {
    let document: Document = serde_json::from_str(PRE_CC8_HDR_SOURCE_SDR_DELIVERY_PROJECT)
        .expect("§7 item 2: it **loads**");
    document.validate().expect("and it validates");

    // The source really is one of §2.1's HDR profiles, so the block below is
    // about an HDR source rather than about an unclassifiable one.
    let source = &document.media_pool[0].color_description;
    assert_eq!(classify_source(source), Ok(ColorSourceProfile::HlgRec2020));

    let report = conformance(&document);
    let blocking = report
        .issues
        .iter()
        .find(|issue| issue.code == HDR_SOURCE_ON_SDR_DELIVERY)
        .expect("§7 item 2's typed reason must be reported");
    assert_eq!(blocking.severity, QaSeverity::Error);
    assert_eq!(blocking.asset, Some(AssetId(1)));
    assert!(
        blocking.message.contains("§0.2 Q6"),
        "the reason must name the deferral: {}",
        blocking.message,
    );
    assert!(!report.export_ready(), "{:?}", issue_codes(&report));

    // The two things §7 item 2 forbids: no rewrite, no tone map. The document
    // is compared to the bytes it came from rather than to a constructed
    // expectation, so any silent repair anywhere in the load or the report
    // shows up here.
    let saved = format!(
        "{}\n",
        serde_json::to_string_pretty(&document).expect("it saves")
    );
    assert_eq!(saved, PRE_CC8_HDR_SOURCE_SDR_DELIVERY_PROJECT);
}

