//! CC8 §9.1 fixture 11 and §7's core half: migration, serialization, and the
//! managed HDR state.
//!
//! §10 step 9 is "Migration and serialization: fixture 11", and fixture 11
//! reads: "**Migration.** An SDR project opens, round-trips, and exports
//! byte-identically; an HDR-source/SDR-delivery project loads and blocks with
//! the typed reason."
//!
//! The half that needs an encoder — "exports byte-identically" — is
//! `kinewright_media::cc8_fixtures`'s, beside §9.1 fixture 6's exported-byte
//! gate. This file carries the half that is pure document state: the stored
//! bytes, the migration rules, §7 item 2's typed block, §7 item 4's
//! save/reopen/journal/undo/redo, and §2.4's static HDR metadata.
//!
//! # The two checked-in projects are real pre-CC8 artifacts
//!
//! `tests/fixtures/pre_cc8_sdr_project.json` and
//! `tests/fixtures/pre_cc8_hdr_source_sdr_delivery_project.json` are byte-frozen
//! project files in the exact form the serializer writes. Their provenance was
//! established rather than assumed: both were loaded and re-serialized by the
//! **pre-CC8 build** (commit `bbf8969`, "feat: complete CC7 workflow
//! evaluation", the last commit before any CC8 code) and came back
//! byte-for-byte, so the bytes this file asserts are unchanged are bytes CC7
//! itself wrote and read. That is what makes §7 item 1's obligation —
//! "**Every existing project opens byte-unchanged and exports byte-identically**"
//! — testable at all: a fixture generated by the build under test could only
//! ever prove self-consistency.
//!
//! CC0's migration precedent is `tests/fixtures/pre_m13_project.json`, which
//! `contracts.rs` and `cc1_conformance.rs` already read for the same purpose;
//! those tests are untouched and still pass, which is the CC0→CC1 half of the
//! same claim.

