/// **§7.** `managed_hdr_v1` is written by CC8 and never by a load.
///
/// §7: "the first CC8 save writes `managed_hdr_v1`; an absent value stays
/// `managed_sdr_v1` or `legacy`." Both halves are asserted here, and the second
/// is asserted on the case that would be most tempting to migrate: a project
/// that already stores an HDR delivery description. CC6 deliberately lets a
/// document hold a delivery target the export refuses, so such a project can
/// exist without CC8; stamping it on load would hand it an HDR export
/// capability it never asked for, which is exactly §7 item 1's "an SDR project
/// must not acquire ... a different exported byte stream".
#[test]
fn cc8_managed_hdr_state_is_written_by_cc8_and_never_stamped_by_a_load() {
    // The state CC8 writes, and its wire spelling.
    let context = ColorContext::hdr_hlg_rec2020();
    assert_eq!(context.pipeline_state, ColorPipelineState::ManagedHdrV1);
    let encoded = serde_json::to_value(&context).expect("the context serialises");
    assert_eq!(encoded["pipeline_state"], "managed_hdr_v1");
    let decoded: ColorContext = serde_json::from_value(encoded).expect("and round-trips");
    assert_eq!(decoded, context);

    // §3.1: only the delivery description differs from CC1's context.
    let sdr = ColorContext::sdr_rec709();
    assert_eq!(context.working, sdr.working);
    assert_eq!(context.monitoring, sdr.monitoring);
    assert_eq!(context.delivery, cc8_hdr_delivery_description());
    assert!(context.is_managed_hdr_compatible());
    assert!(!context.is_managed_sdr_compatible());
    assert!(context.is_managed_compatible());

    // An absent `pipeline_state` on a context that already names §5.1's lane
    // stays `legacy` — never `managed_hdr_v1`, and never `managed_sdr_v1`.
    let absent = serde_json::json!({
        "working": sdr.working,
        "monitoring": sdr.monitoring,
        "delivery": cc8_hdr_delivery_description(),
    });
    let migrated: ColorContext = serde_json::from_value(absent).expect("it loads");
    assert_eq!(migrated.pipeline_state, ColorPipelineState::Legacy);
    assert!(!migrated.is_managed_compatible());

    // A stored `managed_sdr_v1` beside an HDR delivery description stays
    // exactly that, and is refused as a managed pipeline rather than being
    // read as the HDR one.
    let mismatched = ColorContext {
        pipeline_state: ColorPipelineState::ManagedSdrV1,
        delivery: cc8_hdr_delivery_description(),
        ..ColorContext::sdr_rec709()
    };
    assert!(!mismatched.is_managed_compatible());
    let document = Document {
        color_context: mismatched,
        ..Document::default()
    };
    let report = conformance(&document);
    assert!(
        issue_codes(&report).contains(&"unsupported_color_pipeline_state".to_owned()),
        "{:?}",
        issue_codes(&report),
    );
    let issue = report
        .issues
        .iter()
        .find(|issue| issue.code == "unsupported_color_pipeline_state")
        .expect("checked above");
    assert!(
        issue.message.contains("managed_hdr_v1"),
        "{}",
        issue.message
    );
    assert!(
        issue.message.contains(CC8_MANAGED_HDR_STATE_RECOVERY),
        "the lane-aware state reason must carry its recovery action: {}",
        issue.message,
    );
}

/// **§7.** The two half-formed colour contexts `SetColorContext` refuses.
///
/// The state and the lane must name each other, in both directions. This is the
/// same rule §7 item 3 applies to the delivery description's own fields, one
/// level up: a project must not be able to store a context whose state and
/// target contradict each other and only fail much later, at export.
#[test]
fn cc8_managed_state_and_delivery_lane_must_name_each_other() {
    let cases = [
        (
            "managed_hdr_v1",
            ColorContext {
                pipeline_state: ColorPipelineState::ManagedHdrV1,
                ..ColorContext::sdr_rec709()
            },
            DeliveryLane::SdrRec709.as_str(),
            DeliveryLane::HdrHlgRec2020.as_str(),
        ),
        (
            "managed_sdr_v1",
            ColorContext {
                pipeline_state: ColorPipelineState::ManagedSdrV1,
                delivery: cc8_hdr_delivery_description(),
                ..ColorContext::sdr_rec709()
            },
            DeliveryLane::HdrHlgRec2020.as_str(),
            DeliveryLane::SdrRec709.as_str(),
        ),
    ];
    for (state, color_context, observed_lane, required_lane) in cases {
        let mut document = Document::default();
        let error = kinewright_core::apply_batch(
            &mut document,
            &[Operation::SetColorContext {
                color_context: color_context.clone(),
            }],
        )
        .expect_err("a half-formed managed context must be refused");
        assert_eq!(
            error,
            BatchError::OperationFailed {
                op_number: 1,
                error: OpError::ManagedColorStateLaneMismatch {
                    state,
                    observed_lane,
                    required_lane,
                    recovery: CC8_MANAGED_HDR_STATE_RECOVERY,
                },
            },
        );
        assert_eq!(
            document.color_context,
            ColorContext::default(),
            "a refused operation must leave the document untouched",
        );
    }

    // The passing direction, both lanes: each state applies on its own lane.
    for context in [ColorContext::sdr_rec709(), ColorContext::hdr_hlg_rec2020()] {
        let mut document = Document::default();
        kinewright_core::apply_batch(
            &mut document,
            &[Operation::SetColorContext {
                color_context: context.clone(),
            }],
        )
        .expect("a matched state and lane must apply");
        assert_eq!(document.color_context, context);
    }

    // `legacy` and a future state are untouched by this rule on the SDR side:
    // CC6 lets a document hold a delivery target its export refuses, and CC1 §4
    // keeps `legacy` readable. Only CC8's own state gained a constraint.
    for state in [
        ColorPipelineState::Legacy,
        ColorPipelineState::Other("managed_sdr_v2".to_owned()),
    ] {
        let mut document = Document::default();
        kinewright_core::apply_batch(
            &mut document,
            &[Operation::SetColorContext {
                color_context: ColorContext {
                    pipeline_state: state.clone(),
                    ..ColorContext::sdr_rec709()
                },
            }],
        )
        .expect("CC8 adds no rule to the SDR states CC1 and CC6 already defined");
        assert_eq!(document.color_context.pipeline_state, state);
    }
}

/// **§7 item 4.** Save/reopen, journal replay, undo, and redo preserve the
/// managed state, the source HDR metadata, and the profile assumption.
///
/// §7 item 4, verbatim: "Save/reopen, journal replay, undo, and redo preserve
/// the source HDR metadata, the profile assumption, and the managed state,
/// byte-for-byte apart from documented JSON defaults."
///
/// Three of the four things it names are stored state and are compared as
/// stored bytes here. The **profile assumption** is not stored anywhere and
/// deliberately so — CC1 §2.1's D65 assumption is derived from the raw
/// description at every call site (`classify_source_with_assumption`,
/// `hdr_source_profile_for_description`, the renderer's own `d65_assumption`),
/// and §2.1 requires the raw metadata to stay `Unknown`: "No code may rewrite
/// it." So the obligation on it is discharged by the description round-tripping
/// unchanged, and that is what is asserted — the same assumption, applied to
/// the same raw white point, yields the same profile after every step.
#[test]
fn cc8_hdr_state_survives_save_reopen_journal_replay_undo_and_redo() {
    let mut asset = kinewright_core::MediaAsset {
        color_description: ColorDescription {
            white_point: ColorWhitePoint::Unknown,
            hdr_static_metadata: declared_static_metadata(),
            ..hlg_source_description()
        },
        ..sdr_asset()
    };
    asset.id = AssetId(1);

    // The starting document: an HDR source, CC1's SDR context.
    let start = Document {
        media_pool: vec![asset.clone()],
        ..Document::default()
    };
    let core = Core::spawn(start).expect("the core starts");
    let operation = Operation::SetColorContext {
        color_context: ColorContext::hdr_hlg_rec2020(),
    };

    let Event::DocumentChanged {
        doc,
        revision: TimelineRevision(1),
        last_op: Some(last_op),
        journal_command: Some(journal_command),
    } = core
        .request(Command::Do(operation.clone()))
        .expect("applied")
    else {
        panic!("expected the HDR context to apply");
    };
    assert_eq!(last_op, operation);
    assert_eq!(journal_command, JournalCommand::Do(operation.clone()));
    assert_hdr_project(&doc, "applied");

    // Save and reopen, on the serialized bytes.
    let saved = serde_json::to_string(doc.as_ref()).expect("it saves");
    let reopened: Document = serde_json::from_str(&saved).expect("it reopens");
    assert_eq!(&reopened, doc.as_ref());
    assert_eq!(
        serde_json::to_string(&reopened).expect("it re-saves"),
        saved,
        "§7 item 4: byte-for-byte apart from documented JSON defaults",
    );
    assert_hdr_project(&Arc::new(reopened), "reopened");

    // Journal replay: the recorded command, through its serialized form, into a
    // fresh core over the same starting document.
    let journal_json = serde_json::to_string(&journal_command).expect("the journal serialises");
    let replayed_command: JournalCommand =
        serde_json::from_str(&journal_json).expect("and deserialises");
    assert_eq!(replayed_command, journal_command);
    let replay_core = Core::spawn(Document {
        media_pool: vec![asset],
        ..Document::default()
    })
    .expect("the replay core starts");
    let Event::DocumentChanged { doc: replayed, .. } = replay_core
        .request(Command::from(replayed_command))
        .expect("the journalled command replays")
    else {
        panic!("expected the replayed command to change the document");
    };
    assert_eq!(
        serde_json::to_string(replayed.as_ref()).expect("the replayed document saves"),
        saved,
        "journal replay must reproduce the same document bytes",
    );

    // Undo, then redo.
    let Event::DocumentChanged { doc: undone, .. } =
        core.request(Command::Undo).expect("undo is accepted")
    else {
        panic!("expected undo to change the document");
    };
    assert_eq!(
        undone.color_context,
        ColorContext::default(),
        "undo must restore the pre-operation context exactly",
    );
    assert_source_preserved(&undone, "undone");

    let Event::DocumentChanged { doc: redone, .. } =
        core.request(Command::Redo).expect("redo is accepted")
    else {
        panic!("expected redo to change the document");
    };
    assert_eq!(
        serde_json::to_string(redone.as_ref()).expect("the redone document saves"),
        saved,
        "redo must reproduce the same document bytes",
    );
    assert_hdr_project(&redone, "redone");
}

/// The managed state, the delivery lane, and the source, on one document.
fn assert_hdr_project(document: &Arc<Document>, label: &str) {
    assert_eq!(
        document.color_context.pipeline_state,
        ColorPipelineState::ManagedHdrV1,
        "{label}",
    );
    assert!(
        document.color_context.is_managed_hdr_compatible(),
        "{label}"
    );
    assert_eq!(
        DeliveryLane::for_description(&document.color_context.delivery),
        DeliveryLane::HdrHlgRec2020,
        "{label}",
    );
    assert_source_preserved(document, label);
}

/// The source description, its declared §2.4 metadata, and the profile the
/// derived D65 assumption still reaches.
fn assert_source_preserved(document: &Document, label: &str) {
    let description = &document.media_pool[0].color_description;
    assert_eq!(
        description.white_point,
        ColorWhitePoint::Unknown,
        "{label}: §2.1 — the raw source metadata stays Unknown",
    );
    assert_eq!(
        description.hdr_static_metadata,
        declared_static_metadata(),
        "{label}: §2.4's declared metadata must survive",
    );
    assert_eq!(
        classify_source_with_assumption(description, Some(ColorSourceProfileAssumption::D65)),
        Ok(ColorSourceProfile::HlgRec2020),
        "{label}: the derived profile assumption must still reach the same profile",
    );
    assert_eq!(
        classify_source(description),
        Err(kinewright_core::ColorSourceError::UnknownWhitePoint),
        "{label}: and it is still an assumption, not a rewritten field",
    );
}

